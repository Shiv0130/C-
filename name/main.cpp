#include <iostream>

using namespace std;

/* Write a c++ program that prints out "access granted " if the user name is ur name and the password is = 12345

Access is only given if the user is above 18yrs of age
Write a c++ program that prints out access granted if conditions are met otherwise access is denied
 */

int main()
{
    string name;
    string password;
    int age;


    cout << "Enter name:";
    cin>>name;

    cout << "Enter password:";
    cin>>password;

    cout << "Enter age:";
    cin>>age;

    if(name=="Shivaar" & age>=18 & password="1234"){
        cout<<"Access granted"<<endl;
    }





    return 0;
}
